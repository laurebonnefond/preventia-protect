/** Helper : module par ID */
export function getModule(id) {
  for (const g of MODULE_GROUPS) {
    const m = g.modules.find(x => x.id === id);
    if (m) return { ...m, group: g };
  }
  return null;
}

/** Helper : modules par statut */
export function getModulesByStatus(status) {
  return MODULE_GROUPS.flatMap(g => g.modules.filter(m => m.status === status).map(m => ({ ...m, group: g })));
}

/** Helper : registre par ID */
export function getRegistre(id) {
  return REGISTRES_OBLIGATOIRES.find(r => r.id === id);
}
